import assert from 'node:assert/strict';
import { demoDispatches, dispatchDate, dispatchDemoAsOf, dispatchEvents, dispatchGroup, dispatchStatus, filterDispatches } from './whatsappDispatches.ts';
const base = { query: '', kind: 'all', period: '7', group: 'all' };
const filter = (extra = {}, records = demoDispatches) => filterDispatches(records, { ...base, ...extra }, dispatchDemoAsOf);
const snapshot = structuredClone(demoDispatches);
assert.equal(filter().length, 8); assert.equal(filter({ period: '30' }).length, 9); assert.equal(filter({ period: 'all' }).length, 10);
assert.equal(filter({ group: 'success' }).length, 4); assert.equal(filter({ group: 'failed' }).length, 2); assert.equal(filter({ group: 'pending' }).length, 2);
assert.equal(dispatchGroup('sent'), 'pending'); assert.equal(dispatchGroup('queued'), 'pending'); assert.equal(dispatchGroup('read'), 'success');
console.log('OK Períodos e contagens sem confundir enviado com entregue');
const boundary = ['2026-10-25T02:59:59Z', '2026-10-25T03:00:00Z', '2026-10-31T15:00:01Z', 'invalid'].map((createdAt, i) => ({ ...demoDispatches[0], id: String(i), createdAt }));
assert.deepEqual(filter({}, boundary).map(r => r.id), ['1']);
assert.match(dispatchDate('2026-10-25T03:00:00Z'), /25\/10\/2026.*00:00:00/); assert.equal(dispatchDate('invalid'), 'Data não disponível');
console.log('OK Limite do dia de Brasília, futuro e datas inválidas');
const reversed = { ...demoDispatches[0], events: [...demoDispatches[0].events].reverse() };
assert.equal(dispatchStatus(reversed), 'read'); assert.equal(dispatchEvents(reversed)[0].status, 'queued'); assert.equal(reversed.events[0].status, 'read');
assert.equal(dispatchStatus({ ...reversed, events: [{ status: 'failed', at: 'invalid' }] }), 'queued');
console.log('OK Evento mais recente e cronologia sem mutar a origem');
assert.equal(filter({ period: 'all', query: 'JOAO' })[0].recipient, 'João de exemplo');
assert.equal(filter({ query: 'DEMO-0002', kind: 'monthly', group: 'failed' }).length, 1);
assert.equal(filter({ query: 'nada encontrado' }).length, 0);
console.log('OK Busca sem acento, identificação e filtros combinados');
const reversedRecords = [...demoDispatches].reverse(), ordered = filterDispatches(reversedRecords, { ...base, period: 'all' }, dispatchDemoAsOf);
assert.equal(ordered[0].id, 'DEMO-0001'); assert.equal(ordered.at(-1).id, 'DEMO-0010'); assert.equal(reversedRecords[0].id, 'DEMO-0010');
assert.deepEqual(demoDispatches, snapshot);
console.log('OK Ordem recente primeiro e registros imutáveis');
console.log('5 grupos passaram.');
