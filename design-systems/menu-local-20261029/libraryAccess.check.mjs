import assert from 'node:assert/strict';
import { mayReadMaterial, validLibraryAudience } from './libraryAccess.ts';
const publicMaterial = { audience: { kind: 'house' } };
const privateMaterial = { audience: { kind: 'individual', memberId: 'a' } };
assert.equal(mayReadMaterial(privateMaterial, { kind: 'zelador' }), true);
assert.equal(mayReadMaterial(privateMaterial, { kind: 'member', memberId: 'a' }), true);
assert.equal(mayReadMaterial(privateMaterial, { kind: 'member', memberId: 'b' }), false);
assert.equal(mayReadMaterial(privateMaterial, { kind: 'member', memberId: '' }), false);
assert.equal(mayReadMaterial(privateMaterial, { kind: 'unknown' }), false);
assert.equal(mayReadMaterial(publicMaterial, { kind: 'member', memberId: 'b' }), true);
assert.equal(mayReadMaterial(publicMaterial, { kind: 'member', memberId: '' }), false);
assert.equal(mayReadMaterial({ audience: { kind: 'individual', memberId: '' } }, { kind: 'member', memberId: '' }), false);
assert.equal(mayReadMaterial({ audience: { kind: 'unexpected' } }, { kind: 'member', memberId: 'a' }), false);
assert.equal(validLibraryAudience(privateMaterial.audience, ['a', 'b']), true);
assert.equal(validLibraryAudience(privateMaterial.audience, ['b']), false);
assert.equal(validLibraryAudience({ kind: 'individual', memberId: '' }, ['a']), false);
assert.equal(validLibraryAudience({ kind: 'unexpected' }, ['a']), false);
assert.equal(validLibraryAudience(publicMaterial.audience, []), true);
console.log('Local library visibility checks passed: exact recipient, explicit house, missing/unknown values fail closed.');
